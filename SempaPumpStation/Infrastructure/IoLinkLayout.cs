using System.Collections.Generic;
using System.Linq;

namespace SempaPumpStation.Infrastructure
{
    /// <summary>The modules of a zone's IO-Link line.</summary>
    public enum IoLinkModule
    {
        /// <summary>BNI00L3 IO-Link master.</summary>
        Master,
        /// <summary>BNI00AJ 8 AI / RTD hub, master port 0 ("IoLink".Zone[z].RtdHub).</summary>
        RtdHub,
        /// <summary>BNI00KM 8 AI hub (zone 3: BNI0007 4 AI), master port 1 ("IoLink".Zone[z].AnalogHub).</summary>
        AnalogHub,
        /// <summary>BNI007Z 16 DI/DO hub, master port 2.</summary>
        DioHub,
    }

    /// <summary>One port of a module, as in the IO list.</summary>
    public sealed class IoLinkPortInfo
    {
        public int Zone;
        public IoLinkModule Module;
        public int Port;
        /// <summary>What the IO list connects here; empty = free.</summary>
        public string Label = "";
        /// <summary>The analog input this port feeds, or null.</summary>
        public string Channel;
        public string Unit = "";
        /// <summary>The instrument position wired here (flowmeter, pressure transmitter, vacuummeter): the library
        /// device mounted on it can be changed. Null for sensors that are not exchanged.</summary>
        public string Position;
        /// <summary>False when the module has no such port (BNI0007 has 4).</summary>
        public bool Present = true;

        public bool IsInstrument => Position != null;
        public bool IsHub => Module == IoLinkModule.RtdHub || Module == IoLinkModule.AnalogHub;
        /// <summary>The port's raw value in "IoLink" (analog hubs only).</summary>
        public string RawTag => IsHub ? IoLinkLayout.Raw(Zone, Module, Port) : null;
    }

    /// <summary>
    /// The IO-Link wiring of the three zones, after Sempa_IO_Listesi (sheets Zone 1–3); ports numbered row by row
    /// as in the sheet. Every sensor has a fixed port; on the instrument positions the device can be exchanged.
    /// Mirrors FB_Station_Instruments (generated by New-StationInstruments.ps1).
    /// </summary>
    public static class IoLinkLayout
    {
        public const int PortCount = 8;
        /// <summary>A 4-20 mA input with nothing connected reads as a wire break.</summary>
        public const int OpenInputRaw = 32767;

        public static readonly IoLinkModule[] Hubs = { IoLinkModule.RtdHub, IoLinkModule.AnalogHub, IoLinkModule.DioHub };

        public static string Raw(int zone, IoLinkModule hub, int port) => "IoLink.Zone[" + zone + "]." + hub + "[" + port + "]";
        public static string Field(int zone, string field) => "IoLink.Zone[" + zone + "]." + field;

        public static string TypeName(int zone, IoLinkModule m)
        {
            switch (m)
            {
                case IoLinkModule.Master: return "BNI00L3";
                case IoLinkModule.RtdHub: return "BNI00AJ";
                case IoLinkModule.AnalogHub: return zone == 3 ? "BNI0007" : "BNI00KM";
                default: return "BNI007Z";
            }
        }

        public static string Description(int zone, IoLinkModule m)
        {
            switch (m)
            {
                case IoLinkModule.Master: return "IO-Link Master";
                case IoLinkModule.RtdHub: return "8 AI / RTD";
                case IoLinkModule.AnalogHub: return zone == 3 ? "4 AI (4-20 mA)" : "8 AI";
                default: return "16 DI/DO";
            }
        }

        /// <summary>The master port a hub is connected to.</summary>
        public static int MasterPort(IoLinkModule hub) => hub == IoLinkModule.RtdHub ? 0 : hub == IoLinkModule.AnalogHub ? 1 : 2;

        /// <summary>Where an instrument position's sensor is wired: hub zone, hub and port.</summary>
        public static (int Zone, IoLinkModule Hub, int Port) Wiring(InstrumentPositionInfo p)
        {
            if (p.Category == Station.Vacuummeter) return (p.Zones[0], IoLinkModule.RtdHub, 5);
            if (p.Category == Station.PressureTransmitter)
                return (p.Zones[0], IoLinkModule.AnalogHub, int.Parse(p.Name.Substring(p.Name.Length - 1)) - 1);
            // Flowmeters: the shared ones on zone 2's hub, zone 3's on its own; FM n on port n-1
            int zone = p.Zones.Contains(3) ? 3 : 2;
            return (zone, IoLinkModule.RtdHub, System.Array.IndexOf(Station.FlowmeterPositions(zone), p.Name));
        }

        /// <summary>
        /// Analog inputs that are not instrument positions: channel → (zone, hub, port), or field ("Vibration" /
        /// "Temperature") for the IO-Link sensor on master port 3.
        /// </summary>
        public static IEnumerable<(string Channel, int Zone, IoLinkModule Hub, int Port, string Field)> FixedInputs()
        {
            for (int z = 1; z <= Station.ZoneCount; z++)
            {
                yield return ("Zone" + z + "_WaterTemperature", z, IoLinkModule.RtdHub, 6, null);
                yield return ("Zone" + z + "_AmbientTemperature", z, IoLinkModule.RtdHub, 7, null);
                if (z == 3)
                {
                    yield return ("Zone3_Speed", 3, IoLinkModule.RtdHub, 3, null);
                    yield return ("Zone3_Sound", 3, IoLinkModule.RtdHub, 4, null);
                }
                else
                {
                    yield return ("Zone" + z + "_Sound", z, IoLinkModule.AnalogHub, 4, null);
                    yield return ("Zone" + z + "_Speed", z, IoLinkModule.AnalogHub, 5, null);
                }
                yield return ("Zone" + z + "_Vibration", z, IoLinkModule.Master, 3, "Vibration");
                yield return ("Zone" + z + "_Temperature", z, IoLinkModule.Master, 3, "Temperature");
            }
        }

        private static readonly Dictionary<string, (string Label, string Unit)> SensorLabels = new Dictionary<string, (string, string)>
        {
            { "WaterTemperature", ("Su sıcaklığı", "°C") },
            { "AmbientTemperature", ("Ortam sıcaklığı", "°C") },
            { "Sound", ("Ses seviyesi", "dB") },
            { "Speed", ("Devir sayısı", "d/dk") },
        };

        private static readonly string[] DioLabels = { "Yeşil ışık", "Pompa Başlat", "Sarı ışık", "Pompa Durdur", "Kırmızı ışık", "Örnek al", "", "EStop" };

        /// <summary>The 8 ports of a module, with what the IO list connects to them.</summary>
        public static IoLinkPortInfo[] Ports(int zone, IoLinkModule module)
        {
            var ports = Enumerable.Range(0, PortCount).Select(p => new IoLinkPortInfo { Zone = zone, Module = module, Port = p }).ToArray();
            switch (module)
            {
                case IoLinkModule.Master:
                    ports[0].Label = TypeName(zone, IoLinkModule.RtdHub);
                    ports[1].Label = TypeName(zone, IoLinkModule.AnalogHub);
                    ports[2].Label = TypeName(zone, IoLinkModule.DioHub);
                    ports[3].Label = "Titreşim & Sıcaklık";
                    break;

                case IoLinkModule.DioHub:
                    for (int p = 0; p < PortCount; p++) ports[p].Label = DioLabels[p];
                    break;

                default:
                    if (module == IoLinkModule.AnalogHub && zone == 3)
                        for (int p = 4; p < PortCount; p++) ports[p].Present = false;

                    foreach (var position in Station.Positions)
                    {
                        var w = Wiring(position);
                        if (w.Zone != zone || w.Hub != module) continue;
                        var port = ports[w.Port];
                        port.Position = position.Name;
                        port.Channel = position.Channel;
                        port.Label = position.Category == Station.Vacuummeter ? "Vakummetre" : position.Label;
                    }
                    foreach (var f in FixedInputs().Where(f => f.Zone == zone && f.Hub == module && f.Field == null))
                    {
                        var (label, unit) = SensorLabels[f.Channel.Substring(f.Channel.IndexOf('_') + 1)];
                        ports[f.Port].Label = label;
                        ports[f.Port].Channel = f.Channel;
                        ports[f.Port].Unit = unit;
                    }
                    break;
            }
            return ports;
        }
    }
}
