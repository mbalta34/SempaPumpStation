# Generates the typed S7 tag models (SiemensS7PlcTag subclasses, RailHMI / HourllandInterface style) from the
# PLC's UDT and DB sources in .\Sources. Re-export those sources from TIA and re-run this script whenever the
# HMI interface of MainPLC changes; the offsets are laid out at run time by S7Cursor, so nothing is hand-counted.
#
#   powershell -NoProfile -ExecutionPolicy Bypass -File Generate-PlcInterface.ps1
param(
    [string] $Sources = (Join-Path $PSScriptRoot 'Sources'),
    [string] $OutDir = (Join-Path $PSScriptRoot 'Generated')
)

# DB numbers in MainPLC
$dbNumbers = [ordered]@{ MaintenanceHp = 101; MaintenancePh = 102; StationHp = 201; StationPh = 202; StationSamples = 203; StationInstruments = 204; IoLink = 205 }

# Types provided by TerakkiFramework.Plc.Hmi (same layout as the PLC's FB_Hmi_* UDTs) or hand-written (DTL)
$external = 'st_Hmi_Hp_CommandButton', 'st_Hmi_Ph_CommandButton', 'st_Hmi_Hp_ParameterInt', 'st_Hmi_Ph_ParameterInt',
            'st_Hmi_Hp_ParameterReal', 'st_Hmi_Ph_ParameterReal', 'st_Hmi_Hp_ParameterBool', 'st_Hmi_Ph_ParameterBool', 'DTL'

$leafTypes = @{ Bool = 'BOOL'; Int = 'INT'; DInt = 'DINT'; UInt = 'UINT'; UDInt = 'UDINT'; USInt = 'USINT'; SInt = 'SINT'; Real = 'REAL' }

function Read-Members([string] $file) {
    $members = @()
    $inBody = $false
    foreach ($raw in [IO.File]::ReadAllLines($file)) {
        $line = ($raw -replace '\{[^}]*\}', '' -replace '//.*$', '').Trim()
        if ($line -match '^(STRUCT|VAR( RETAIN)?)$') { $inBody = $true; continue }
        if ($line -match '^(END_STRUCT;?|END_VAR)$') { $inBody = $false; continue }
        if (-not $inBody -or $line -eq '') { continue }
        if ($line -notmatch '^"?(\w+)"?\s*:\s*(.+?)\s*(:=.*)?;$') { throw "Cannot parse member in ${file}: $raw" }
        $members += [pscustomobject]@{ Name = $Matches[1]; Type = $Matches[2].Trim() }
    }
    return $members
}

function Parse-Type([string] $t) {
    if ($t -match '^Array\[(\d+)\.\.(\d+)\] of (.+)$') {
        $e = Parse-Type $Matches[3]
        return [pscustomobject]@{ Kind = 'Array'; Lo = [int]$Matches[1]; Hi = [int]$Matches[2]; Element = $e }
    }
    if ($t -match '^String\[(\d+)\]$') { return [pscustomobject]@{ Kind = 'String'; Length = [int]$Matches[1] } }
    if ($t -match '^"(\w+)"$') { return [pscustomobject]@{ Kind = 'Struct'; Name = $Matches[1] } }
    if ($t -eq 'DTL') { return [pscustomobject]@{ Kind = 'Struct'; Name = 'DTL' } }
    if ($leafTypes.ContainsKey($t)) { return [pscustomobject]@{ Kind = 'Leaf'; DataType = $leafTypes[$t] } }
    throw "Unsupported type: $t"
}

function Emit-Class([string] $className, $members, [string] $summary, [bool] $isDb, [int] $dbNumber) {
    $L = [Collections.Generic.List[string]]::new()
    $L.Add('// <auto-generated> Generate-PlcInterface.ps1 from PlcInterface\Sources. Do not edit by hand. </auto-generated>')
    $L.Add('using System.Collections.Generic;')
    $L.Add('using TerakkiFramework.Communication.Abstractions;')
    $L.Add('using TerakkiFramework.Plc;')
    $L.Add('using TerakkiFramework.Plc.Hmi;')
    $L.Add('using TerakkiFramework.Plc.Siemens;')
    $L.Add('')
    $L.Add('namespace SempaPumpStation.PlcInterface')
    $L.Add('{')
    $L.Add("    /// <summary>$summary</summary>")
    $L.Add("    public class $className : SiemensS7PlcTag")
    $L.Add('    {')
    if ($isDb) {
        $L.Add("        public const int Number = $dbNumber;")
        $L.Add('')
        $L.Add("        public $className(IConnectionService c, WriteDispatchMode w, ReadPlan r)")
        $L.Add("            : this(c, `"$($className -replace 'Db$','')`", Number, 0, w, r) { }")
        $L.Add('')
    }
    $L.Add("        public $className(IConnectionService c, string name, int db, int byteOffset, WriteDispatchMode w, ReadPlan r)")
    $L.Add('            : base(c, name, "DB" + db + ".DBB" + byteOffset, DataType.STRUCT, w, r)')
    $L.Add('        {')
    $L.Add('            var k = new S7Cursor(c, db, byteOffset, w, r);')
    $props = @()
    foreach ($m in $members) {
        $t = Parse-Type $m.Type
        $n = $m.Name
        switch ($t.Kind) {
            'Leaf' {
                $L.Add("            $n = k.Leaf(name + `".$n`", DataType.$($t.DataType));")
                $props += "        public SiemensS7PlcTag $n { get; private set; }"
            }
            'String' {
                $L.Add("            $n = k.Leaf(name + `".$n`", DataType.STRING, $($t.Length));")
                $props += "        public SiemensS7PlcTag $n { get; private set; }"
            }
            'Struct' {
                $L.Add("            $n = k.Next(new $($t.Name)(c, name + `".$n`", db, k.Struct(), w, r));")
                $props += "        public $($t.Name) $n { get; private set; }"
            }
            'Array' {
                if ($t.Element.Kind -eq 'Leaf' -and $t.Element.DataType -ne 'BOOL') {
                    # Array of numbers: word-aligned start, elements packed (Bool arrays pack bits; not needed yet)
                    $L.Add("            $n = new List<SiemensS7PlcTag>();")
                    $L.Add('            k.ArrayStart();')
                    $L.Add("            for (int i = $($t.Lo); i <= $($t.Hi); i++)")
                    $L.Add("                $n.Add(k.Leaf(name + `".$n[`" + i + `"]`", DataType.$($t.Element.DataType)));")
                    $props += "        public List<SiemensS7PlcTag> $n { get; private set; }"
                    continue
                }
                if ($t.Element.Kind -ne 'Struct') { throw "Only arrays of structs or numbers are supported ($className.$n)" }
                $e = $t.Element.Name
                $L.Add("            $n = new List<$e>();")
                $L.Add('            k.ArrayStart();')
                $L.Add("            for (int i = $($t.Lo); i <= $($t.Hi); i++)")
                $L.Add("                $n.Add(k.Next(new $e(c, name + `".$n[`" + i + `"]`", db, k.Struct(), w, r)));")
                $props += "        public List<$e> $n { get; private set; }"
            }
        }
    }
    $L.Add('        }')
    $L.Add('')
    foreach ($p in $props) { $L.Add($p) }
    $L.Add('    }')
    $L.Add('}')
    $L.Add('')
    [IO.File]::WriteAllText((Join-Path $OutDir "$className.cs"), ($L -join "`r`n"), (New-Object Text.UTF8Encoding $false))
}

New-Item -ItemType Directory -Force $OutDir | Out-Null
Get-ChildItem $OutDir -Filter *.cs | Remove-Item

$count = 0
foreach ($f in Get-ChildItem $Sources -Filter *.udt) {
    $name = $f.BaseName
    if ($external -contains $name) { continue }
    Emit-Class $name (Read-Members $f.FullName) "PLC data type $name." $false 0
    $count++
}
foreach ($f in Get-ChildItem $Sources -Filter *.db) {
    $db = $f.BaseName
    if (-not $dbNumbers.Contains($db)) { throw "No DB number for $db" }
    Emit-Class ($db + 'Db') (Read-Members $f.FullName) "Global DB `"$db`" (DB$($dbNumbers[$db])), standard access." $true $dbNumbers[$db]
    $count++
}
"Generated $count classes in $OutDir"
